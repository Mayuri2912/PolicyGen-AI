REVIEW_NOTICE = (
    "AI-assisted draft. This document was generated by PolicyGen AI from the uploaded source documents. It must be reviewed, "
    "completed and approved by the organization's authorized personnel before it is adopted. It is not legal advice and "
    "does not certify compliance with any law, regulation or standard."
)
SIMULATED_NOTICE = (
    "SIMULATED OUTPUT (mock mode). This draft was assembled by rule-based templates without an AI model, for demonstration "
    "and testing only. Do not treat its analysis as genuine."
)
ORIGIN_LABELS = {
    "generated": "Generated",
    "regenerated": "Sections regenerated",
    "ai_revision": "AI-assisted revision",
    "user_edit": "Edited by user",
}
_UNKNOWN = "[To be confirmed: {}]"


def _or_placeholder(value: str, what: str) -> str:
    return value.strip() if value and value.strip() else _UNKNOWN.format(what)


def _format_date(value: str) -> str:
    try:
        return date.fromisoformat(value).strftime("%d %B %Y")
    except (TypeError, ValueError):
        return _UNKNOWN.format("effective date")


def _status(policy: Policy, version: PolicyVersion) -> str:
    if policy.approved_version == version.version_number:
        event = next(
            (e for e in reversed(policy.review_events) if e.action == "approve" and e.version_number == version.version_number),
            None,
        )
        if event:
            return f"Approved by {event.actor} on {event.created_at.strftime('%d %B %Y')} (as recorded in PolicyGen AI)"
        return "Approved (as recorded in PolicyGen AI)"
    if version.version_number == policy.current_version:
        if policy.review_status == "in_review":
            return "Draft - submitted for review"
        if policy.review_status == "changes_requested":
            return "Draft - changes requested by reviewer"
    return "Draft - not approved"


def _source_text(item: dict) -> str:
    source = item.get("source") or {}
    if not source.get("file_name"):
        return "Inferred - no direct source"
    return f"{source['file_name']}" + (f" ({source['location']})" if source.get("location") else "")


def _appendices(config: PolicyConfig, content: dict, findings: dict, summary: dict) -> list[dict]:
    requirements, risks, controls, gaps = findings["requirement"], findings["risk"], findings["control"], findings["gap"]
    appendices: list[dict] = []

    if config.include_risk_register and risks:
        method = scoring.scoring_method()
        ordered = sorted(risks, key=lambda r: -r.get("score", 0))
        appendices.append(
            {
                "id": "appendix_risk_register",
                "title": "Risk Register",
                "elements": [
                    {
                        "type": "paragraph",
                        "text": "Risks are scored as likelihood multiplied by impact, each on a scale of 1 to 5. Levels: "
                        + ", ".join(f"{b['label']} {b['range']}" for b in method["levels"])
                        + ". 'Documented' risks are evidenced in the source documents; 'Inferred' risks were deduced by the "
                        "analysis and are possibilities to review, not confirmed weaknesses or incidents.",
                    },
                    {"type": "risk_matrix", "cells": scoring.risk_matrix(risks)},
                    {
                        "type": "table",
                        "columns": ["ID", "Risk", "L", "I", "Level", "Origin", "Existing controls", "Recommended mitigation"],
                        "widths": [9, 20, 4, 4, 9, 12, 19, 23],
                        "rows": [
                            [
                                r["ref_id"],
                                f"{r['title']}" + (f" [{r['category']}]" if r.get("category") else ""),
                                str(r.get("likelihood") or "-"),
                                str(r.get("impact") or "-"),
                                f"{scoring.LEVEL_LABELS.get(r.get('level'), 'Unrated')} ({r.get('score', 0)})",
                                ("Documented" if r.get("origin") == "documented" else "Inferred")
                                + (", rating estimated" if r.get("scoring_basis") == "estimated" else ""),
                                "; ".join(r.get("existing_controls") or []) or "None documented",
                                r.get("recommended_mitigation") or "-",
                            ]
                            for r in ordered
                        ],
                    },
                ],
            }
        )

    if config.include_control_matrix and (controls or requirements):
        matrix = mapping.control_matrix(requirements, risks, controls, gaps)
        elements = []
        if matrix:
            elements.append(
                {
                    "type": "table",
                    "columns": ["Requirement", "Assessment", "Related risks", "Existing controls", "Recommended controls"],
                    "widths": [34, 13, 11, 21, 21],
                    "rows": [
                        [
                            f"{row['requirement_id']} {row['requirement']}",
                            row["status_label"],
                            ", ".join(row["risk_ids"]) or "-",
                            "; ".join(f"{c['id']} {c['name']}" for c in row["existing_controls"]) or "None evidenced",
                            "; ".join(f"{c['id']} {c['name']}" for c in row["recommended_controls"]) or "-",
                        ]
                        for row in matrix
                    ],
                }
            )
        if controls:
            elements += [
                {"type": "subheading", "text": "Control Catalogue"},
                {
                    "type": "table",
                    "columns": ["ID", "Control", "Type", "Function", "Status", "Basis", "Source"],
                    "widths": [8, 30, 12, 11, 13, 11, 15],
                    "rows": [
                        [
                            c["ref_id"],
                            c["name"] + (f": {c['description']}" if c.get("description") and c["description"] != c["name"] else ""),
                            c.get("control_type", "").title(),
                            c.get("control_function", "").title(),
                            c.get("status_label", ""),
                            "Existing" if c.get("basis") == "existing" else "Recommended",
                            _source_text(c),
                        ]
                        for c in controls
                    ],
                },
            ]
        appendices.append({"id": "appendix_control_matrix", "title": "Control Matrix", "elements": elements})

    if config.include_gap_analysis and gaps:
        appendices.append(
            {
                "id": "appendix_gap_analysis",
                "title": "Gap Analysis",
                "elements": [
                    {"type": "note", "text": ASSESSMENT_DISCLAIMER},
                    {
                        "type": "table",
                        "columns": ["Requirement", "Assessment", "Identified gap", "Priority", "Suggested action"],
                        "widths": [30, 13, 24, 9, 24],
                        "rows": [
                            [
                                f"{g['requirement_id']} {g.get('requirement', '')}",
                                g.get("status_label", ""),
                                g.get("identified_gap") or "-",
                                g.get("priority", "").title(),
                                g.get("suggested_action") or "-",
                            ]
                            for g in gaps
                        ],
                    },
                ],
            }
        )

    if config.include_source_references:
        lookup = {item["ref_id"]: item for kind in ("requirement", "risk", "control") for item in findings[kind]}
        rows = []
        for section in content["sections"]:
            for block in section["blocks"]:
                for statement in block.get("statements", []):
                    refs = [r for r in statement.get("refs", []) if r in lookup]
                    sources = list(dict.fromkeys(_source_text(lookup[r]) for r in refs))
                    rows.append(
                        [
                            statement.get("id", ""),
                            "Documented" if statement.get("basis") == "documented" else "Proposed",
                            ", ".join(refs) or "-",
                            "; ".join(sources) or "No source: proposed by this draft",
                        ]
                    )
        elements = [
            {
                "type": "paragraph",
                "text": "This appendix links each policy statement to the analysis findings that support it and to the uploaded "
                "document and location those findings came from.",
            }
        ]
        if rows:
            elements.append(
                {
                    "type": "table",
                    "columns": ["Statement", "Basis", "Supporting findings", "Source document and location"],
                    "widths": [12, 13, 25, 50],
                    "rows": rows,
                }
            )
        appendices.append({"id": "appendix_evidence", "title": "Evidence Mapping", "elements": elements})

    missing = summary.get("missing_information") or []
    contradictions = summary.get("contradictions") or []
    assumptions = summary.get("assumptions") or []
    if missing or contradictions or assumptions:
        elements = []
        if missing:
            elements += [
                {"type": "subheading", "text": "Information Not Found in the Source Documents"},
                {
                    "type": "table",
                    "columns": ["Missing information", "Why it matters", "Suggested owner"],
                    "widths": [32, 44, 24],
                    "rows": [[m.get("item", ""), m.get("why_it_matters", "") or "-", m.get("suggested_owner", "") or "-"] for m in missing],
                },
            ]
        if contradictions:
            elements += [
                {"type": "subheading", "text": "Contradictions Between Source Documents"},
                {
                    "type": "bullets",
                    "items": [
                        f"{c['topic']}: {c['description']} Sources: "
                        + "; ".join(f"{s['file_name']}" + (f" - {s['detail']}" if s.get("detail") else "") for s in c.get("sources", []))
                        for c in contradictions
                    ],
                },
            ]
        if assumptions:
            elements += [{"type": "subheading", "text": "Assumptions Made by the Analysis"}, {"type": "bullets", "items": assumptions}]
        appendices.append({"id": "appendix_open_items", "title": "Outstanding Information and Assumptions", "elements": elements})
    return appendices


# Column proportions for the tables whose shape is fixed by the template.
_TABLE_WIDTHS = {("abbreviations", 2): [24, 76], ("definitions", 2): [28, 72], ("roles_responsibilities", 3): [24, 50, 26]}


def _with_widths(section_id: str, block: dict) -> dict:
    widths = _TABLE_WIDTHS.get((section_id, len(block.get("columns") or []))) if block.get("type") == "table" else None
    return {**block, "widths": widths} if widths else block


def build_document_model(policy: Policy, version: PolicyVersion, analysis: Analysis) -> dict:
    """Assemble everything a renderer needs for one policy version."""
    config = PolicyConfig.model_validate(policy.config)
    template = get_template(policy.policy_type)
    content = version.content
    findings = findings_by_kind(analysis, include_excluded=False)
    summary = analysis.summary or {}

    organization = _or_placeholder(config.organization_name, "organization name")
    files = policy.source_files or []
    meta = {
        "title": content.get("title") or template.name,
        "policy_type": template.name,
        "policy_code": template.code,
        "organization": organization,
        "department": config.department,
        "classification": config.classification or "Internal",
        "document_version": config.document_version or "1.0",
        "revision": version.version_number,
        "status": _status(policy, version),
        "generated_on": iso(version.created_at),
        "simulated": policy.simulated,
        "generator": "PolicyGen AI (mock mode - rule-based, no AI model)" if policy.simulated else f"PolicyGen AI using {policy.model} ({PROVIDER_LABELS.get(policy.provider, policy.provider)})",
        "source_files": [f["file_name"] for f in files],
    }
    document_control = [
        ["Document title", meta["title"]],
        ["Organization", organization],
        ["Department", _or_placeholder(config.department, "department")],
        ["Policy owner", _or_placeholder(config.policy_owner, "policy owner")],
        ["Approver", _or_placeholder(config.approver, "approver")],
        ["Document version", f"{meta['document_version']} (draft revision {version.version_number})"],
        ["Status", meta["status"]],
        ["Effective date", _format_date(config.effective_date)],
        ["Review frequency", _or_placeholder(config.review_frequency, "review frequency")],
        ["Classification", meta["classification"]],
        ["Source documents", ", ".join(meta["source_files"]) or "-"],
        ["Generated by", meta["generator"]],
    ]
    history = [
        [
            str(v.version_number),
            v.created_at.strftime("%d %b %Y"),
            ORIGIN_LABELS.get(v.origin, v.origin),
            v.change_note or "-",
        ]
        for v in policy.versions
        if v.version_number <= version.version_number
    ]

    # Headings are numbered from the order of the sections, so the numbers and
    # the table of contents always follow the template order.
    sections = []
    for number, section in enumerate(content["sections"], start=1):
        sections.append(
            {
                "id": section["id"],
                "number": str(number),
                "title": section["heading"],
                "kind": "section",
                "origin": section.get("origin", "ai_generated"),
                "elements": [_with_widths(section["id"], block) for block in section["blocks"]],
            }
        )
    for index, appendix in enumerate(_appendices(config, content, findings, summary)):
        letter = chr(ord("A") + index)
        sections.append(
            {
                "id": appendix["id"],
                "number": f"Appendix {letter}",
                "title": appendix["title"],
                "kind": "appendix",
                "origin": "system",
                "elements": appendix["elements"],
            }
        )

    return {
        "meta": meta,
        "notices": [SIMULATED_NOTICE, REVIEW_NOTICE] if policy.simulated else [REVIEW_NOTICE],
        "document_control": document_control,
        "version_history": history,
        "sections": sections,
    }


def section_label(section: dict) -> str:
    """Heading text as rendered: '3. Scope' or 'Appendix A - Risk Register'."""
    if section["kind"] == "appendix":
        return f"{section['number']} - {section['title']}"
    return f"{section['number']}. {section['title']}"
